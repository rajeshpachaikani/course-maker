export function AdminNavItem({
  href,
  label,
  icon,
  badge,
}: {
  href:
    | "/admin"
    | "/admin/courses"
    | "/admin/appearance"
    | "/admin/settings"
    | "/admin/users";
  label: string;
  icon: IconKey;
  badge?: number | string;
}) {
  const pathname = usePathname();
  const active =
    href === "/admin"
      ? pathname === "/admin"
      : pathname === href || pathname.startsWith(`${href}/`);
  return (
    <Link
      href={href}
      className={`admin-nav-item ${active ? "active" : ""}`}
    >
      {ICONS[icon]}
      <span>{label}</span>
      {badge !== undefined && badge !== null && badge !== "" ? (
        <span className="badge">{badge}</span>
      ) : null}
    </Link>
  );
}
